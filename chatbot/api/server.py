"""FastAPI backend for the recruitment chatbot — the API half of chatbot/.

Separate module from the CLI (workers/chat.py) but reuses its retrieval and
prompt pieces, so CLI and web answers stay identical. The static frontend
(chatbot/frontend) is served by this process locally and can be hosted
elsewhere later by pointing its config.js at this API. This half stays
in-network: it needs the DB and (directly or via the embedding service)
the BGE-M3 model.

Scale features (all env-tunable, safe defaults for laptop dev):
  CHATBOT_API_TOKEN      shared bearer token; unset = auth off (local dev)
  CHATBOT_ALLOWED_ORIGINS comma-separated CORS origins (default localhost:8000)
  CHATBOT_RATE_LIMIT     chat requests/min per client IP (default 20, 0 = off)
  CHATBOT_DB_POOL_SIZE   Postgres connection pool size (default 5)
  CHATBOT_WORKERS        uvicorn worker processes (default 1) — with >1 set
                         EMBED_SERVICE_URL or every worker loads the 2 GB model
  EMBED_SERVICE_URL      embedding microservice (embed_service.py); unset =
                         load BGE-M3 in-process
  CHATBOT_HOST           bind address (default 127.0.0.1; 0.0.0.0 in Docker)

Endpoints: GET /api/health, POST /api/chat (JSON), POST /api/chat/stream (SSE:
meta -> token* -> done, or error).

Run:  py chatbot/api/server.py
"""

