@app.post("/api/warmup", dependencies=[Depends(require_token)])
def warmup() -> dict:
    """Fire a 1-token LLM call to trigger the Qwen GPU cold start ahead of real
    use. The frontend calls this on page load (best-effort) so the model is
    booting while the recruiter reads/types, hiding most of the ~1-3 min cold
    start. Cheap: one token, and it no-ops fast once the container is warm."""
    model_name = os.environ.get("LLM_MODEL", "llama-3.3-70b-versatile")
    try:
        state["client"].chat.completions.create(
            model=model_name, messages=[{"role": "user", "content": "ping"}],
            max_tokens=1,
        )
        return {"warm": True}
    except Exception as exc:  # never surface details — this is best-effort
        log.info("warmup call failed (model likely still booting): %s", exc)
        return {"warm": False}


