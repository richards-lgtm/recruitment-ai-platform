@app.post("/api/chat", dependencies=[Depends(require_token), Depends(rate_limit)])
def chat(req: ChatRequest) -> dict:
    rid = uuid.uuid4().hex[:8]
    t_start = time.perf_counter()
    messages, model_name, jobs, timings = prepare(req, rid)
    t0 = time.perf_counter()
    try:
        resp = state["client"].chat.completions.create(model=model_name, messages=messages)
    except Exception as exc:
        log.error("[%s] LLM request failed: %s", rid, exc)
        status, payload = llm_error_payload(exc)
        raise HTTPException(status_code=status, detail=payload)
    timings["llm_ms"] = round((time.perf_counter() - t0) * 1000)
    timings["total_ms"] = round((time.perf_counter() - t_start) * 1000)
    log.info("[%s] chat qlen=%d %s", rid, len(req.question), timings)
    answer = resp.choices[0].message.content
    # Chip only the postings the answer actually cites — the full retrieval
    # context (up to 6 jobs) confuses users when most weren't relevant.
    cited = set(extract_job_ids(answer or ""))
    return {"answer": answer, "jobs": [j for j in jobs if j["job_id"] in cited]}


# Providers phrase retry hints like "try again in 51m40.895s" / "in 7.66s".
RETRY_HINT_RE = re.compile(r"try again in (?:(\d+)h)?(?:(\d+)m)?([\d.]+)s", re.IGNORECASE)


def llm_error_payload(exc: Exception) -> tuple[int, dict]:
    """Map an LLM-call failure to (http_status, {code, message}) that is safe
    to show users. The raw exception (org ids, quota numbers) is logged by the
    caller — never sent to the browser."""
    raw = str(exc)
    status = getattr(exc, "status_code", None)
    if status == 429:
        message = "The AI service has reached its usage limit."
        hint = RETRY_HINT_RE.search(raw)
        if hint:
            hours, mins, secs = (int(hint.group(1) or 0), int(hint.group(2) or 0),
                                 float(hint.group(3)))
            total_min = hours * 60 + mins + (1 if secs > 0 else 0)
            message += (f" Try again in about {total_min} minute(s)."
                        if total_min > 1 else " Try again in a minute.")
        else:
            message += " Please try again in a few minutes."
        return 429, {"code": "llm_rate_limited", "message": message}
    if status in (401, 403):
        return 502, {"code": "llm_auth_failed",
                     "message": "The AI service rejected the server's credentials — "
                                "the LLM API key needs attention."}
    if status is None:  # connection/timeout errors have no HTTP status
        return 502, {"code": "llm_unreachable",
                     "message": "Could not reach the AI service. Please try again; "
                                "if it persists, contact the admin."}
    return 502, {"code": "llm_error",
                 "message": "The AI service failed to answer. Please try again."}


def sse(event: str, data: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(data)}\n\n"


@app.post("/api/chat/stream",
          dependencies=[Depends(require_token), Depends(rate_limit)])
def chat_stream(req: ChatRequest) -> StreamingResponse:
    rid = uuid.uuid4().hex[:8]

    def event_stream():
        t_start = time.perf_counter()
        try:
            messages, model_name, jobs, timings = prepare(req, rid)
            yield sse("meta", {"jobs": jobs})
            t0 = time.perf_counter()
            stream = state["client"].chat.completions.create(
                model=model_name, messages=messages, stream=True
            )
            for chunk in stream:
                delta = chunk.choices[0].delta.content if chunk.choices else None
                if delta:
                    yield sse("token", {"t": delta})
            timings["llm_ms"] = round((time.perf_counter() - t0) * 1000)
            timings["total_ms"] = round((time.perf_counter() - t_start) * 1000)
            log.info("[%s] stream qlen=%d %s", rid, len(req.question), timings)
            yield sse("done", {})
        except Exception as exc:  # stream already started — report in-band
            log.error("[%s] stream failed: %s", rid, exc)
            _, payload = llm_error_payload(exc)
            yield sse("error", payload)

    return StreamingResponse(
        event_stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


